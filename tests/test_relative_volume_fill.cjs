'use strict';
const assert=require('node:assert/strict');
const {relativeVolumeFill}=require('../android-chart.js');
const bars=Array.from({length:52},(_,i)=>({timestamp:i*300000,open:100,high:102,low:99,close:101,volume:i+1,closed:i!==51}));
assert.equal(relativeVolumeFill(bars,50,false),1,'all prior 50 lower');
assert.equal(relativeVolumeFill(bars,51,false),null,'open candle must not fill');
assert.equal(relativeVolumeFill(bars,49,false),null,'50 prior closed candles required');
const equal=bars.map(x=>({...x,volume:10}));
assert.equal(relativeVolumeFill(equal,50,false),0,'ties are not counted as lower');
const noVolume=bars.map(x=>({...x}));
noVolume[50].volume=NaN;
assert.equal(relativeVolumeFill(noVolume,50,false),null,'missing current volume');
noVolume[50].volume=51;noVolume[4].volume=NaN;
assert.equal(relativeVolumeFill(noVolume,50,false),null,'missing reference volume');
const negative=bars.map(x=>({...x}));negative[3].volume=-1;
assert.equal(relativeVolumeFill(negative,50,false),null,'negative volume');
const noClosed=bars.map(x=>({...x}));noClosed[3].closed=false;
assert.equal(relativeVolumeFill(noClosed,50,false),null,'forming reference candle');
const doji=bars.map(x=>({...x}));doji[50].open=doji[50].close;
assert.equal(relativeVolumeFill(doji,50,false),1,'doji percentile valid but no body to fill');
const zero=bars.map(x=>({...x}));zero[50].volume=0;
assert.equal(relativeVolumeFill(zero,50,false),0,'zero volume is valid but ranks zero');
console.log('PASS relative volume: closed/open, 50 prior, ties, missing, doji, zero, negative');
