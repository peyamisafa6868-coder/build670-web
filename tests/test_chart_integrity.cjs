const assert=require('node:assert/strict');
const integrity=require('../chart-integrity.js');
const pivot=require('../chart-support-levels.js');
const bars=Array.from({length:260},(_,i)=>{
 const base=100+4*Math.sin(i/7),t=1700000000000+i*300000;
 return {timestamp:t,open:base-.2,high:base+.7,low:base-.7,close:base+.2,volume:1000+i,closed:true};
});
const quality=integrity.inspect({candles:bars,lastBarClosed:true,interval:'5m'});
assert.equal(quality.valid,true);
assert.equal(quality.spikes.length,0);
const extreme=bars.map(x=>({...x}));extreme[230].high=extreme[230].close+40;
const warning=integrity.inspect({candles:extreme,lastBarClosed:true,interval:'5m'});
assert.equal(warning.valid,true,'Extreme wick cannot be silently removed');
assert.ok(warning.spikes.some(x=>x.index===230));
assert.equal(warning.providerCompared,false,'No external raw feed comparison was made');
const malformed=bars.map(x=>({...x}));malformed[33].low=malformed[33].high+1;
assert.equal(integrity.inspect({candles:malformed,lastBarClosed:true,interval:'5m'}).valid,false);
const repeat=bars.map(x=>({...x}));repeat[40].timestamp=repeat[39].timestamp;
assert.equal(integrity.inspect({candles:repeat,lastBarClosed:true,interval:'5m'}).valid,false);
const first=pivot.compute(bars,{lastBarClosed:true});
const unlabeled=bars.map(({closed,...rest})=>rest);
const second=pivot.compute(unlabeled,{lastBarClosed:true});
assert.deepEqual(first,second,'Explicitly verified lastBarClosed can establish historical bar closure');
assert.equal(pivot.compute(unlabeled,{lastBarClosed:false}).closedCount,259);
const close=100;
const s=integrity.mergeLevels('support',close,[{price:97.04,source:'CONFIRMED_PIVOT',bandHalfWidth:.06}],{price:97,bandHalfWidth:0},.1,3);
assert.equal(s.length,1);assert.equal(s[0].price,97,'Kotlin source price must not shift');
assert.equal(s[0].source,'KOTLIN_REFERENCE+CONFIRMED_PIVOT');
const r=integrity.mergeLevels('resistance',close,[{price:103,source:'CONFIRMED_PIVOT'}],{price:103.02},.1,2);
assert.equal(r.length,1);
const layout=integrity.layoutLabels([{y:50,priority:0},{y:52,priority:1},{y:54,priority:2}],10,100,18);
assert.equal(layout.length,3);assert.equal(layout[0].labelY,50);
for(let i=0;i<layout.length;i++)for(let j=i+1;j<layout.length;j++)assert.ok(Math.abs(layout[i].labelY-layout[j].labelY)>=18);
console.log(JSON.stringify({status:'passed',type:'DATA_INTEGRITY_SOURCE_AXIS',checks:13,spikeIndex:230,source:s[0].source}));
